//! Build-script half of the harness: turns an existing test module into
//! guest code plus a [`TestCase`](crate::TestCase) list.
//!
//! A guest cannot compile the module as-is. Outside `cargo test`, rustc
//! drops every `#[test]` function, so the collector removes those
//! attributes, makes the functions `pub(crate)` so the generated list can
//! name them from nested modules, and appends `ZKCI_TESTS` and
//! `ZKCI_EXCLUDED`. Bodies, helpers and imports are copied unchanged.
//!
//! A guest includes the result into a module named like the original:
//!
//! ```ignore
//! mod tests {
//!     include!(concat!(env!("OUT_DIR"), "/example_tests.rs"));
//! }
//! ```

use std::{fs, path::Path};

use quote::quote;
use syn::{parse_quote, Attribute, Ident, Item, ItemFn, ReturnType};

/// What [`collect`] found in a test module.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Collected {
    /// libtest names of the tests that will run, in source order.
    pub runnable: Vec<String>,
    /// libtest names of the tests that will not, with the reason.
    pub excluded: Vec<(String, String)>,
}

/// Rewrites the test module at `source` for a guest and writes it to `out`.
///
/// `module` is the module's path in its own crate (`tests` for
/// `#[cfg(test)] mod tests;` at the crate root). It prefixes every name, so
/// names match `cargo test` output. Panics on I/O or parse errors, which is
/// how a build script reports them.
pub fn collect(source: impl AsRef<Path>, module: &str, out: impl AsRef<Path>) -> Collected {
    let source = source.as_ref();
    println!("cargo:rerun-if-changed={}", source.display());
    let text = fs::read_to_string(source)
        .unwrap_or_else(|e| panic!("zkci: reading {}: {e}", source.display()));
    let (code, collected) = rewrite(&text, module)
        .unwrap_or_else(|e| panic!("zkci: parsing {}: {e}", source.display()));
    fs::write(out.as_ref(), code)
        .unwrap_or_else(|e| panic!("zkci: writing {}: {e}", out.as_ref().display()));
    collected
}

/// The pure part of [`collect`]: returns the generated source.
pub fn rewrite(source: &str, module: &str) -> syn::Result<(String, Collected)> {
    let mut file = syn::parse_file(source)?;
    // `include!` rejects inner attributes. A test module's are its `//!`
    // docs and lint levels, neither of which the guest needs.
    file.attrs.clear();

    let mut walker = Walker {
        module,
        path: Vec::new(),
        cases: Vec::new(),
        collected: Collected::default(),
    };
    walker.walk(&mut file.items, false);

    let cases = walker.cases.iter().map(|case| {
        let (name, path) = (&case.name, &case.path);
        // A unit test is already a `fn()`. Only a test that returns
        // something (a `Result`) needs the `Outcome` wrapper.
        let run = if case.returns {
            quote! { || ::zkci_harness::Outcome::check(#(#path)::*()) }
        } else {
            quote! { #(#path)::* }
        };
        quote! { ::zkci_harness::TestCase { name: #name, run: #run } }
    });
    let excluded = walker.collected.excluded.iter().map(|(name, reason)| {
        quote! { ::zkci_harness::Excluded { name: #name, reason: #reason } }
    });
    file.items.push(parse_quote! {
        /// Every runnable test in this module, in source order.
        pub(crate) static ZKCI_TESTS: &[::zkci_harness::TestCase] = &[#(#cases),*];
    });
    file.items.push(parse_quote! {
        /// Tests found but not runnable in a guest.
        pub(crate) static ZKCI_EXCLUDED: &[::zkci_harness::Excluded] = &[#(#excluded),*];
    });

    let code = format!(
        "// @generated by zkci_harness::build from a test module. Do not edit.\n\n{}",
        prettyplease::unparse(&file)
    );
    Ok((code, walker.collected))
}

struct Walker<'a> {
    module: &'a str,
    /// Inline modules between the test module and the current item.
    path: Vec<Ident>,
    cases: Vec<Case>,
    collected: Collected,
}

/// A runnable test, for the generated list.
struct Case {
    /// The libtest name.
    name: String,
    /// Path from the test module to the function.
    path: Vec<Ident>,
    /// Whether the function has a return type (`-> Result<..>`).
    returns: bool,
}

enum Kind {
    NotATest,
    Runnable,
    Excluded(String),
}

impl Walker<'_> {
    /// `gated` is true inside a `#[cfg]`-gated module: its tests are
    /// reported as excluded and the items are left exactly as they are.
    fn walk(&mut self, items: &mut Vec<Item>, gated: bool) {
        items.retain_mut(|item| match item {
            Item::Fn(f) => match classify(f, gated) {
                Kind::NotATest => true,
                Kind::Runnable => {
                    f.attrs.retain(|a| !is_test_attr(a));
                    f.vis = parse_quote!(pub(crate));
                    let mut path = self.path.clone();
                    path.push(f.sig.ident.clone());
                    let name = self.name(&f.sig.ident);
                    self.collected.runnable.push(name.clone());
                    self.cases.push(Case {
                        name,
                        path,
                        returns: !matches!(f.sig.output, ReturnType::Default),
                    });
                    true
                }
                Kind::Excluded(reason) => {
                    let name = self.name(&f.sig.ident);
                    self.collected.excluded.push((name, reason));
                    // Gated items stay for the compiler to drop. Anything
                    // else goes, since its body may need what the guest
                    // lacks (an executor, unwinding).
                    gated
                }
            },
            Item::Mod(m) => {
                let gated = gated || has_cfg(&m.attrs);
                if let Some((_, content)) = &mut m.content {
                    self.path.push(m.ident.clone());
                    self.walk(content, gated);
                    self.path.pop();
                }
                true
            }
            _ => true,
        });
    }

    fn name(&self, ident: &Ident) -> String {
        let mut name = self.module.to_owned();
        for segment in self.path.iter().chain([ident]) {
            name.push_str("::");
            name.push_str(&segment.to_string());
        }
        name
    }
}

fn classify(f: &ItemFn, gated: bool) -> Kind {
    let Some(attr) = f.attrs.iter().find(|a| is_test_attr(a)) else {
        return Kind::NotATest;
    };
    let path = attr.path();
    let excluded = |reason: &str| Kind::Excluded(reason.to_owned());
    // Reasons a guest can never run the test come first, so the report
    // names the real blocker rather than a cfg the collector skipped.
    if f.sig.asyncness.is_some() {
        excluded("async test: needs an executor (design §8, Async)")
    } else if has_attr(&f.attrs, "should_panic") {
        excluded("#[should_panic]: needs unwinding, and a guest is panic = \"abort\"")
    } else if !is_builtin_test(path) {
        let path = quote!(#path).to_string().replace(' ', "");
        Kind::Excluded(format!("custom test attribute #[{path}]"))
    } else if has_attr(&f.attrs, "ignore") {
        excluded("#[ignore]")
    } else if gated || has_cfg(&f.attrs) {
        excluded("cfg-gated: the collector does not evaluate cfg")
    } else {
        Kind::Runnable
    }
}

/// `#[test]`, `#[tokio::test]`, `#[core::prelude::v1::test]`, …
fn is_test_attr(attr: &Attribute) -> bool {
    attr.path()
        .segments
        .last()
        .is_some_and(|s| s.ident == "test")
}

/// The libtest attribute itself, by any of its spellings.
fn is_builtin_test(path: &syn::Path) -> bool {
    let segments: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    match segments.as_slice() {
        [test] => test == "test",
        [root, prelude, _, test] => {
            (root == "core" || root == "std") && prelude == "prelude" && test == "test"
        }
        _ => false,
    }
}

fn has_attr(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|a| a.path().is_ident(name))
}

fn has_cfg(attrs: &[Attribute]) -> bool {
    has_attr(attrs, "cfg") || has_attr(attrs, "cfg_attr")
}

#[cfg(test)]
mod tests {
    use super::*;

    const FIXTURE: &str = r#"
//! Module docs, which `include!` would reject.
#![allow(clippy::all)]

use serde_json::json;

fn helper() -> u32 { 1 }

#[test]
fn plain() { assert_eq!(helper(), 1); }

#[test]
fn returns_result() -> Result<(), String> { Ok(()) }

#[test]
#[ignore]
fn slow() {}

#[test]
#[should_panic]
fn panics() { panic!() }

#[tokio::test]
async fn needs_runtime() {}

#[test_log::test]
fn custom() {}

#[test]
#[cfg(feature = "x")]
fn gated() {}

#[cfg(debug_assertions)]
#[test]
#[should_panic(expected = "arity")]
fn debug_only_panics() {}

mod nested {
    #[core::prelude::v1::test]
    fn inner() {}
}

#[cfg(unix)]
mod unix_only {
    #[test]
    fn inner() {}
}
"#;

    #[test]
    fn classifies_every_test_in_the_fixture() {
        let (_, collected) = rewrite(FIXTURE, "tests").unwrap();
        assert_eq!(
            collected.runnable,
            [
                "tests::plain",
                "tests::returns_result",
                "tests::nested::inner"
            ]
        );
        let excluded: Vec<(&str, &str)> = collected
            .excluded
            .iter()
            .map(|(n, r)| (n.as_str(), r.split(": ").next().unwrap()))
            .collect();
        assert_eq!(
            excluded,
            [
                ("tests::slow", "#[ignore]"),
                ("tests::panics", "#[should_panic]"),
                ("tests::needs_runtime", "async test"),
                ("tests::custom", "custom test attribute #[test_log::test]"),
                ("tests::gated", "cfg-gated"),
                ("tests::debug_only_panics", "#[should_panic]"),
                ("tests::unix_only::inner", "cfg-gated"),
            ]
        );
    }

    #[test]
    fn generated_module_keeps_helpers_and_drops_test_attributes() {
        let (code, _) = rewrite(FIXTURE, "tests").unwrap();
        let file = syn::parse_file(&code).expect("generated code parses");
        assert!(file.attrs.is_empty(), "inner attributes break include!");
        assert!(code.contains("fn helper()"));
        assert!(code.contains("pub(crate) fn plain()"));
        assert!(code.contains("nested::inner"));
        // Excluded bodies are gone, so nothing they need is compiled.
        assert!(!code.contains("needs_runtime()"));
        // The cfg-gated module is kept verbatim for the compiler to drop,
        // so its `#[test]` is the only one left.
        assert!(code.contains("#[cfg(unix)]"));
        assert_eq!(code.matches("#[test]").count(), 1);
        assert!(!code.contains("prelude::v1::test"));
        assert!(code.contains("pub(crate) static ZKCI_TESTS"));
        // Unit tests are listed as plain fn pointers; only the Result test
        // goes through the Outcome wrapper.
        assert!(code.contains("run: plain"));
        assert_eq!(code.matches("Outcome::check").count(), 1);
        assert!(code.contains("pub(crate) static ZKCI_EXCLUDED"));
    }

    #[test]
    fn rewrite_reports_parse_errors() {
        assert!(rewrite("fn (", "tests").is_err());
    }
}
