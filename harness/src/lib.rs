//! Runs a crate's existing `#[test]` functions inside a zkVM guest, or
//! natively, and reports the outcome as one serializable value.
//!
//! Two halves:
//!
//! - **Build time** ([`build`], feature `build`): a guest's build script
//!   points [`build::collect`] at a test module such as
//!   `api-types/src/tests.rs`. It writes a copy of that module with the
//!   `#[test]` attributes removed (a non-test build would otherwise drop the
//!   functions) and appends the [`TestCase`] list. Test bodies are not
//!   touched, and the original file is not modified.
//! - **Run time** ([`run`]): calls every case in order on the current thread
//!   and returns a [`SuiteReport`], which the guest commits as its public
//!   values.
//!
//! Collection happens at build time, not through `inventory` or `linkme`:
//! both depend on linker sections or life-before-main, which a zkVM guest
//! does not promise to support.

#[cfg(feature = "build")]
pub mod build;

use serde::{Deserialize, Serialize};

/// Version of the [`SuiteReport`] layout. Bump it on any change to the
/// report's fields: the report is bincode-encoded, so an old verifier
/// would otherwise misread a new report rather than reject it.
pub const REPORT_VERSION: u32 = 1;

/// One runnable test, as generated by [`build::collect`].
#[derive(Clone, Copy)]
pub struct TestCase {
    /// The libtest name, e.g. `tests::api_response_ok_shape`, so results
    /// line up with `cargo test` output.
    pub name: &'static str,
    /// Calls the test function. Panics on failure.
    pub run: fn(),
}

/// A `#[test]` the collector found but cannot run in a guest.
#[derive(Clone, Copy)]
pub struct Excluded {
    /// The libtest name.
    pub name: &'static str,
    /// Why it was left out, e.g. an async test with no executor.
    pub reason: &'static str,
}

/// What a guest commits as its public values.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SuiteReport {
    /// [`REPORT_VERSION`] at the time the guest was built.
    pub version: u32,
    /// Which suite ran, e.g. `api-types`.
    pub suite: String,
    /// The git tree hash of the commit under test, as the prover supplied
    /// it. On its own it is only a label. What binds the proof to that
    /// tree is the verifier rebuilding the guest from it and getting the
    /// same verifying key.
    pub tree: String,
    /// One entry per [`TestCase`], in run order.
    pub results: Vec<TestResult>,
    /// Tests the collector found but left out, so a report can never
    /// silently cover fewer tests than the crate has.
    pub excluded: Vec<ExcludedTest>,
}

/// The outcome of one [`TestCase`].
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct TestResult {
    /// The libtest name.
    pub name: String,
    /// Whether the test returned without panicking.
    pub passed: bool,
}

/// An [`Excluded`] test, owned for serialization.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExcludedTest {
    /// The libtest name.
    pub name: String,
    /// Why it was left out.
    pub reason: String,
}

impl SuiteReport {
    /// Number of tests that passed.
    pub fn passed(&self) -> usize {
        self.results.iter().filter(|r| r.passed).count()
    }

    /// Number of tests that failed.
    pub fn failed(&self) -> usize {
        self.results.len() - self.passed()
    }

    /// True when at least one test ran and none failed.
    pub fn is_pass(&self) -> bool {
        !self.results.is_empty() && self.failed() == 0
    }
}

/// Runs every case in order on the current thread.
///
/// Natively, a panicking test is caught and recorded as failed. A zkVM
/// guest is built with `panic = "abort"`, so there a failing test halts the
/// guest with a non-zero exit code and no report is committed at all: no
/// passing proof can exist for a failing suite.
pub fn run(suite: &str, tree: String, cases: &[TestCase], excluded: &[Excluded]) -> SuiteReport {
    let results = cases
        .iter()
        .map(|case| TestResult {
            name: case.name.to_owned(),
            passed: std::panic::catch_unwind(case.run).is_ok(),
        })
        .collect();
    SuiteReport {
        version: REPORT_VERSION,
        suite: suite.to_owned(),
        tree,
        results,
        excluded: excluded
            .iter()
            .map(|e| ExcludedTest {
                name: e.name.to_owned(),
                reason: e.reason.to_owned(),
            })
            .collect(),
    }
}

/// What a test function may return, mirroring libtest's `Termination`
/// for the two shapes unit tests use. The generated cases call
/// `Outcome::check(test_fn())`.
pub trait Outcome {
    /// Panics if the test reported failure.
    fn check(self);
}

impl Outcome for () {
    fn check(self) {}
}

impl<E: std::fmt::Debug> Outcome for Result<(), E> {
    fn check(self) {
        if let Err(e) = self {
            panic!("test returned Err: {e:?}");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ok() {}

    fn fails() {
        panic!("expected failure");
    }

    #[test]
    fn run_records_pass_and_fail_in_order() {
        let cases = [
            TestCase {
                name: "t::ok",
                run: ok,
            },
            TestCase {
                name: "t::fails",
                run: fails,
            },
        ];
        let excluded = [Excluded {
            name: "t::slow",
            reason: "ignored",
        }];
        let report = run("s", "abc".into(), &cases, &excluded);
        assert_eq!(report.version, REPORT_VERSION);
        assert_eq!(report.suite, "s");
        assert_eq!(report.tree, "abc");
        assert_eq!(
            report.results,
            vec![
                TestResult {
                    name: "t::ok".into(),
                    passed: true
                },
                TestResult {
                    name: "t::fails".into(),
                    passed: false
                },
            ]
        );
        assert_eq!(report.excluded[0].reason, "ignored");
        assert_eq!((report.passed(), report.failed()), (1, 1));
        assert!(!report.is_pass());
    }

    #[test]
    fn empty_suite_is_not_a_pass() {
        assert!(!run("s", String::new(), &[], &[]).is_pass());
    }

    #[test]
    fn result_outcome_panics_on_err() {
        Outcome::check(Ok::<(), String>(()));
        let caught = std::panic::catch_unwind(|| Outcome::check(Err::<(), _>("boom")));
        assert!(caught.is_err());
    }
}
